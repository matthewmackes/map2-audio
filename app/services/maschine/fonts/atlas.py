"""Bitmap font atlases for Maschine MK1 LCD rendering."""

from __future__ import annotations

from dataclasses import dataclass, field
from functools import lru_cache


GlyphRows = tuple[str, ...]


@dataclass(frozen=True)
class BitmapFontAtlas:
    family: str
    pixel_width: int
    pixel_height: int
    glyphs: dict[str, GlyphRows]
    tracking: int = 1
    baseline: int = 0
    aliases: dict[str, str] = field(default_factory=dict)
    notes: str = ""

    def glyph(self, char: str) -> GlyphRows:
        token = self.aliases.get(char, char)
        if token in self.glyphs:
            return self.glyphs[token]
        upper = token.upper()
        if upper in self.glyphs:
            return self.glyphs[upper]
        return self.glyphs.get(" ", ("0" * self.pixel_width,) * self.pixel_height)

    def text_width(self, text: str) -> int:
        if not text:
            return 0
        return (len(text) * (self.pixel_width + self.tracking)) - self.tracking


