def _scale_glyph(rows: GlyphRows, *, scale_x: int, scale_y: int) -> GlyphRows:
    output: list[str] = []
    for row in rows:
        scaled_row = "".join(bit * scale_x for bit in row)
        for _ in range(scale_y):
            output.append(scaled_row)
    return tuple(output)


def _scale_font(
    family: str,
    *,
    base: dict[str, GlyphRows],
    scale_x: int,
    scale_y: int,
    tracking: int,
    notes: str,
    aliases: dict[str, str] | None = None,
) -> BitmapFontAtlas:
    width = len(next(iter(base.values()))[0]) * scale_x
    height = len(next(iter(base.values()))) * scale_y
    return BitmapFontAtlas(
        family=family,
        pixel_width=width,
        pixel_height=height,
        glyphs={char: _scale_glyph(rows, scale_x=scale_x, scale_y=scale_y) for char, rows in base.items()},
        tracking=tracking,
        aliases=dict(aliases or {}),
        notes=notes,
    )


